from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
from PIL import Image
from tqdm import tqdm

import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import Dataset, DataLoader
import torchvision.transforms as transforms

import config
from predict import TemporalPredictor
from evaluate import compute_ade, compute_fde


# =========================================================
# Global Transforms
# =========================================================

# Standard ImageNet transform; later you can swap in augmentation.
TRAIN_TRANSFORM = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize(
        mean=config.IMAGE_MEAN,
        std=config.IMAGE_STD,
    ),
])

VAL_TRANSFORM = TRAIN_TRANSFORM  # usually no augmentation for val


# =========================================================
# Trajectory Dataset
# =========================================================

class TrajectoryDataset(Dataset):
    """
    PyTorch Dataset for trajectory prediction.

    Loads samples from a processed_*.json file produced by
    dataset_builder.py. Each entry contains:

        log_id: str
        image_path: str
        timestamp_ns: int
        track_uuid: str
        category: str
        history: [[x, y], ...]  # relative coords
        future: [[x, y], ...]   # relative coords

    The dataset returns:
        image    : Tensor (C, H, W), normalized for ResNet18
        history  : Tensor (H, 2)
        future   : Tensor (F, 2)
        category : str (for class-wise analysis later)
    """

    def __init__(
        self,
        json_path: str | Path,
        transform: transforms.Compose,
    ) -> None:
        super().__init__()

        path = Path(json_path)
        if not path.exists():
            raise FileNotFoundError(path)

        with path.open("r", encoding="utf-8") as f:
            self.samples: List[Dict] = json.load(f)

        self.transform = transform

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Dict[str, object]:
        sample = self.samples[idx]

        image_path = Path(sample["image_path"])
        if not image_path.exists():
            raise FileNotFoundError(image_path)

        image = Image.open(image_path).convert("RGB")
        image_tensor = self.transform(image)  # (C, H, W)

        history = np.array(sample["history"], dtype=np.float32)  # (H, 2)
        future = np.array(sample["future"], dtype=np.float32)    # (F, 2)

        history_tensor = torch.from_numpy(history)  # (H, 2)
        future_tensor = torch.from_numpy(future)    # (F, 2)

        category = sample.get("category", "")

        return {
            "image": image_tensor,
            "history": history_tensor,
            "future": future_tensor,
            "category": category,
        }


# =========================================================
# Dataloader Factory
# =========================================================

def create_dataloader(
    json_path: str | Path,
    batch_size: int,
    shuffle: bool,
    drop_last: bool,
    transform: transforms.Compose,
) -> DataLoader:
    """
    Create a DataLoader for a given processed_*.json file.
    """
    dataset = TrajectoryDataset(json_path=json_path, transform=transform)

    num_workers = config.NUM_WORKERS
    pin_memory = torch.cuda.is_available()
    persistent_workers = num_workers > 0

    loader = DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=pin_memory,
        persistent_workers=persistent_workers,
        prefetch_factor=2,
        drop_last=drop_last,
    )
    return loader


# =========================================================
# Training / Validation Epochs
# =========================================================

def train_one_epoch(
    model: TemporalPredictor,
    dataloader: DataLoader,
    optimizer: optim.Optimizer,
    device: torch.device,
    scaler: torch.cuda.amp.GradScaler | None,
    epoch: int,
    num_epochs: int,
) -> float:
    """
    Train the model for one epoch.

    Returns:
        avg_train_loss
    """
    model.train()
    loss_fn = nn.MSELoss()

    running_loss = 0.0
    num_batches = 0

    use_amp = (scaler is not None and device.type == "cuda")

    pbar = tqdm(dataloader, desc=f"Epoch {epoch+1}/{num_epochs} [train]")
    for batch in pbar:
        images = batch["image"].to(device)    # (B, C, H, W)
        history = batch["history"].to(device) # (B, H, 2)
        future = batch["future"].to(device)   # (B, F, 2)

        optimizer.zero_grad(set_to_none=True)

        if use_amp:
            with torch.cuda.amp.autocast():
                pred_future = model(history, images)
                loss = loss_fn(pred_future, future)
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()
        else:
            pred_future = model(history, images)
            loss = loss_fn(pred_future, future)
            loss.backward()
            optimizer.step()

        running_loss += loss.item()
        num_batches += 1

        pbar.set_postfix({"loss": f"{loss.item():.4f}"})

    avg_loss = running_loss / max(num_batches, 1)
    return avg_loss


@torch.no_grad()
def validate(
    model: TemporalPredictor,
    dataloader: DataLoader,
    device: torch.device,
) -> Tuple[float, float, float]:
    """
    Validate the model on a validation set.

    Returns:
        avg_val_loss, avg_ADE, avg_FDE
    """
    model.eval()
    loss_fn = nn.MSELoss()

    running_loss = 0.0
    running_ade = 0.0
    running_fde = 0.0
    num_batches = 0

    pbar = tqdm(dataloader, desc="[val]")
    for batch in pbar:
        images = batch["image"].to(device)
        history = batch["history"].to(device)
        future = batch["future"].to(device)

        pred_future = model(history, images)
        loss = loss_fn(pred_future, future)

        ade = compute_ade(pred_future, future)
        fde = compute_fde(pred_future, future)

        running_loss += loss.item()
        running_ade += ade
        running_fde += fde
        num_batches += 1

        pbar.set_postfix(
            {
                "loss": f"{loss.item():.4f}",
                "ade": f"{ade:.4f}",
                "fde": f"{fde:.4f}",
            }
        )

    avg_loss = running_loss / max(num_batches, 1)
    avg_ade = running_ade / max(num_batches, 1)
    avg_fde = running_fde / max(num_batches, 1)

    return avg_loss, avg_ade, avg_fde


# =========================================================
# Checkpoint Utilities
# =========================================================

def save_checkpoint(
    model: TemporalPredictor,
    optimizer: optim.Optimizer,
    path: str | Path,
    epoch: int,
    val_loss: float,
) -> None:
    """
    Save model and optimizer state to a given path.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    torch.save(
        {
            "epoch": epoch,
            "model_state_dict": model.state_dict(),
            "optimizer_state_dict": optimizer.state_dict(),
            "val_loss": val_loss,
        },
        path.as_posix(),
    )


# =========================================================
# High-level Training Function
# =========================================================

def train() -> None:
    """
    Main training routine.

    Steps:
        - Create dataloaders
        - Initialize model and optimizer
        - Train/validate for N epochs
        - Save best model by validation loss
    """
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # Paths to processed JSON files from dataset_builder.py
    data_root = Path(config.PROCESSED_DATASET_DIR)
    train_json = data_root / "processed_train.json"
    val_json = data_root / "processed_val.json"

    batch_size = config.BATCH_SIZE
    num_epochs = config.EPOCHS
    lr = config.LEARNING_RATE
    wd = config.WEIGHT_DECAY

    # Dataloaders
    train_loader = create_dataloader(
        json_path=train_json,
        batch_size=batch_size,
        shuffle=True,
        drop_last=True,
        transform=TRAIN_TRANSFORM,
    )
    val_loader = create_dataloader(
        json_path=val_json,
        batch_size=batch_size,
        shuffle=False,
        drop_last=False,
        transform=VAL_TRANSFORM,
    )

    # Model
    model = TemporalPredictor().to(device)

    # Optimizer
    optimizer = optim.Adam(model.parameters(), lr=lr, weight_decay=wd)

    # AMP scaler (optional)
    scaler = torch.cuda.amp.GradScaler() if device.type == "cuda" else None

    best_val_loss = float("inf")
    checkpoint_dir = Path(config.MODEL_DIR)
    checkpoint_dir.mkdir(parents=True, exist_ok=True)
    best_model_path = checkpoint_dir / "best_model.pt"

    for epoch in range(num_epochs):
        train_loss = train_one_epoch(
            model=model,
            dataloader=train_loader,
            optimizer=optimizer,
            device=device,
            scaler=scaler,
            epoch=epoch,
            num_epochs=num_epochs,
        )

        val_loss, val_ade, val_fde = validate(
            model=model,
            dataloader=val_loader,
            device=device,
        )

        print(
            f"Epoch {epoch+1}/{num_epochs} "
            f"| train_loss={train_loss:.4f} "
            f"| val_loss={val_loss:.4f} "
            f"| val_ADE={val_ade:.4f} "
            f"| val_FDE={val_fde:.4f}"
        )

        # Save best model by validation loss
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            save_checkpoint(
                model=model,
                optimizer=optimizer,
                path=best_model_path,
                epoch=epoch + 1,
                val_loss=val_loss,
            )
            print(f"Saved best model to {best_model_path} (val_loss={val_loss:.4f})")


# =========================================================
# Entry Point
# =========================================================

def main() -> None:
    """
    Entry point for training script.
    """
    train()


if __name__ == "__main__":
    main()
